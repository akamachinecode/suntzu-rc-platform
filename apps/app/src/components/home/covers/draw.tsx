import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { renderToStaticMarkup } from "react-dom/server";
import { ApartPose } from "@/components/figures/apart/preview";
import type { Slot } from "@/components/figures/apart/live";
import type { ApartSpec } from "@/components/figures/apart/spec";
import { SLOTS as CAR_SLOTS } from "@/components/figures/car-apart/art";
import { CAR_SPEC } from "@/components/figures/car-apart/spec";
import { SLOTS as HELI_SLOTS } from "@/components/figures/heli-apart/art";
import { HELI_SPEC } from "@/components/figures/heli-apart/spec";
import { SLOTS as PLANE_SLOTS } from "@/components/figures/plane-apart/art";
import { PLANE_SPEC } from "@/components/figures/plane-apart/spec";

/**
 * Draws the guide covers of the home page as standalone SVG files, with the figure kit's styles
 * inside. Only covers.test.tsx imports this (never a page): the figures' geometry stays out of
 * the site, which shows the files as images. `pnpm --filter @workspace/app covers` rewrites them.
 */

type Cover = {
  spec: ApartSpec;
  slots: Slot[];
  apart?: number;
  lit: string;
  /** The part of the drawing to keep, as a viewBox: each still is cropped to its pose. */
  view: [number, number, number, number];
};

export const COVERS = {
  plane: { spec: PLANE_SPEC, slots: PLANE_SLOTS, lit: "wing", view: [84, 102, 448, 338] },
  heli: {
    spec: HELI_SPEC,
    slots: HELI_SLOTS,
    apart: 0.16,
    lit: "blades",
    view: [86, 97, 486, 367],
  },
  car: { spec: CAR_SPEC, slots: CAR_SLOTS, apart: 0.2, lit: "body", view: [136, 123, 412, 311] },
} satisfies Record<string, Cover>;

export type CoverName = keyof typeof COVERS;

const require = createRequire(import.meta.url);
const read = (path: string | URL) => readFileSync(path, "utf8");

/**
 * The styles a cover needs, taken from where the page gets them so the files can't drift:
 * the kit's stylesheet, SunTzu RC's figure overrides in globals.css (the primer-grey tones and
 * the yellow lit assembly) and the theme colours those overrides point at.
 */
function coverStyles() {
  const kit = read(new URL("../../iso/iso.css", import.meta.url));
  const site = read(new URL("../../../app/globals.css", import.meta.url)).replace(
    /\/\*[\s\S]*?\*\//g,
    "",
  );
  const theme = read(require.resolve("@workspace/ui/globals.css"));

  // Top-level rules for the figure on the page (`.iso.servo-figure`) and the exploded figures (`.pla`).
  // A selector starts after the previous rule or statement (`@import …;`).
  const rules = [...site.matchAll(/([^{};]+)\{([^{}]*)\}/g)]
    .filter(([, selector]) => /^\s*\.(iso\.servo-figure|servo-figure \.pla)/.test(selector))
    .map(([rule]) => rule.trim());

  // The theme's light colours (`:root`), for the var(--background)-style values in those rules.
  const root = /:root\s*\{([^}]*)\}/.exec(theme)?.[1] ?? "";
  const tokens = new Map(
    [...root.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]),
  );
  const resolved = rules
    .join("\n")
    .replace(/var\(--([\w-]+)\)/g, (match, name: string) => tokens.get(name) ?? match);

  return `${kit}\n${resolved}`.replace(/\s+/g, " ").replace(/\s*([{};,>])\s*/g, "$1");
}

/**
 * The width a cover is shown at, in CSS pixels: 295 on wide screens and 330 on phones (checked
 * 2026-11-10). The kit
 * draws lines with a fixed screen thickness (`non-scaling-stroke`), but an image is scaled as a
 * whole, so the file is drawn at the size it is shown at to keep its lines as on the page.
 */
const SHOWN_WIDTH = 310;

/** One cover as the text of an .svg file. */
export function drawCover(name: CoverName) {
  const cover: Cover = COVERS[name];
  const [, , viewWidth, viewHeight] = cover.view;
  const width = SHOWN_WIDTH;
  const height = Math.round((SHOWN_WIDTH * viewHeight) / viewWidth);
  const svg = renderToStaticMarkup(
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={cover.view.join(" ")}
      width={width}
      height={height}
      className="iso servo-figure iso-svg"
      data-theme="light"
    >
      <style>{coverStyles()}</style>
      <g className="pla" data-focus="">
        <ApartPose spec={cover.spec} slots={cover.slots} apart={cover.apart} lit={cover.lit} />
      </g>
    </svg>,
  );
  // No double hyphen in the comment: XML forbids it, and browsers then refuse the whole image.
  return `<!-- Generated by src/components/home/covers/draw.tsx (pnpm covers in apps/app). Don't edit. -->\n${svg}\n`;
}
