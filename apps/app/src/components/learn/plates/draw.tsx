import { renderToStaticMarkup } from "react-dom/server";
import { BalanceArt } from "@/components/figures/balance/art";
import { SwashplateArt } from "@/components/figures/swashplate/art";
import { ThumbToElevatorArt } from "@/components/figures/thumb-to-elevator/art";
import { figureStyles } from "@/components/home/covers/draw";

/**
 * Draws the Learn page's plates: three of the guides' figures at rest, as standalone SVG files
 * with the figure kit's styles inside. The page shows them as images, so it stays light (an
 * interactive figure is 50 to 130 KB of markup sent twice); each plate links to its live figure
 * in the guide. Only plates.test.tsx imports this. `pnpm --filter @workspace/app covers`
 * redraws them with the home's covers.
 */
type Plate = {
  Art: () => React.ReactElement;
  /** The part of the drawing to keep, as a viewBox: its extent at rest plus a margin. */
  view: [number, number, number, number];
};

export const PLATES = {
  // Lessons: the stick on your transmitter, followed to the elevator.
  lessons: { Art: ThumbToElevatorArt, view: [10, 14, 620, 301] },
  // Your first model: finding the balance point before the first flight.
  "first-model": { Art: BalanceArt, view: [5, 7, 630, 307] },
  // Advanced: the swashplate, where helicopter flying gets serious.
  advanced: { Art: SwashplateArt, view: [76, -15, 489, 473] },
} satisfies Record<string, Plate>;

export type PlateName = keyof typeof PLATES;

/** The figures' own rules in globals.css, and the figure on the page. */
const PLATE_RULES = /^\s*\.(iso\.servo-figure|servo-figure )/;

/**
 * The width a plate is shown at on a phone, in CSS pixels. The kit draws lines at a fixed screen
 * thickness, but an image is scaled as a whole, so the file is drawn at the size it is shown at
 * on the screens most visitors have; on a desktop it is shown a little larger.
 */
export const SHOWN_WIDTH = 360;

/** One plate as the text of an .svg file. */
export function drawPlate(name: PlateName) {
  const { Art, view }: Plate = PLATES[name];
  const markup = renderToStaticMarkup(<Art />);
  // The figure is a <div> (its controls and labels) around one <svg>: keep the drawing, and the
  // div's class, which the figure's styles hang from (`.servo-figure .tte .iso-svg`).
  const start = markup.indexOf("<svg");
  const end = markup.lastIndexOf("</svg>") + "</svg>".length;
  const wrapper = /^<div[^>]*\bclass="([^"]*)"/.exec(markup)?.[1] ?? "";
  const svg = markup.slice(start, end);
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (start < 0 || !viewBox) throw new Error(`No drawing in the ${name} figure`);
  const [, , width, height] = view;
  const shown = Math.round((SHOWN_WIDTH * height) / width);
  // The figure's own drawing keeps its size and place; the file shows the `view` part of it.
  const [, , fullWidth, fullHeight] = viewBox.split(/\s+/).map(Number);
  const classes = wrapper
    .split(/\s+/)
    .filter((token) => /^[\w-]+$/.test(token))
    .join(" ");
  const style = figureStyles(PLATE_RULES);
  // No double hyphen in the comment: XML forbids it, and browsers then refuse the whole image.
  return [
    "<!-- Generated by src/components/learn/plates/draw.tsx (pnpm covers in apps/app). Don't edit. -->",
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${view.join(" ")}" width="${SHOWN_WIDTH}" height="${shown}" class="iso servo-figure" data-theme="light">`,
    `<style>${style}</style>`,
    `<g class="${classes}">${svg.replace("<svg", `<svg x="0" y="0" width="${fullWidth}" height="${fullHeight}" overflow="visible"`)}</g>`,
    "</svg>",
    "",
  ].join("\n");
}
